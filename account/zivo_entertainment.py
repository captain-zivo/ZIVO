def _scope(scope_key: Any) -> str:
    return str(scope_key)


def _pick(kind: str, items: Sequence[Any], scope_key: Any) -> Any:
    if not items:
        return None
    scope = _scope(scope_key)
    key = (scope, kind)
    history = _history[key]
    candidates = [i for i in range(len(items)) if i not in history]
    if not candidates:
        history.clear()
        candidates = list(range(len(items)))
    index = _rng.choice(candidates)
    history.append(index)
    return items[index]


