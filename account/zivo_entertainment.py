def _remote_get_sync(url: str) -> Tuple[str, str]:
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "ZIVO/59 (+SoroushPlus)",
            "Accept": "application/json,text/plain,text/html;q=0.9,*/*;q=0.8",
        },
    )
    with urllib.request.urlopen(request, timeout=REMOTE_TIMEOUT) as response:
        content_type = response.headers.get("Content-Type", "")
        raw = response.read(64 * 1024)
    return raw.decode("utf-8", errors="replace"), content_type


async def _remote_get(url: str) -> Tuple[str, str]:
    return await asyncio.wait_for(
        asyncio.to_thread(_remote_get_sync, url),
        timeout=REMOTE_TIMEOUT + 2.0,
    )


def _clean_remote_text(value: str) -> str:
    value = html.unescape(str(value or ""))
    value = re.sub(r"<br\s*/?>", "\n", value, flags=re.I)
    value = re.sub(r"<[^>]+>", " ", value)
    value = value.replace("\r", "\n")
    value = re.sub(r"[ \t]+", " ", value)
    value = re.sub(r"\n[ \t]+", "\n", value)
    value = re.sub(r"\n{3,}", "\n\n", value)
    return value.strip(" \n\t\ufeff")


def _walk_json_strings(obj: Any, out: List[Tuple[str, str]], key: str = "") -> None:
    if isinstance(obj, str):
        text = _clean_remote_text(obj)
        if text:
            out.append((key.lower(), text))
        return
    if isinstance(obj, dict):
        for child_key, child in obj.items():
            _walk_json_strings(child, out, str(child_key))
        return
    if isinstance(obj, list):
        for child in obj:
            _walk_json_strings(child, out, key)


def _extract_remote_candidate(body: str, content_type: str) -> str:
    body = (body or "").strip()
    if not body:
        return ""
    looks_json = "json" in (content_type or "").lower() or body[:1] in "[{"
    if looks_json:
        try:
            parsed = json.loads(body)
            strings: List[Tuple[str, str]] = []
            _walk_json_strings(parsed, strings)
            preferred = (
                "joke", "story", "text", "content", "result", "description",
                "poem", "ghazal", "interpretation", "tafsir", "title",
            )
            for wanted in preferred:
                for key, text in strings:
                    if wanted in key and len(text) >= 20:
                        return text
            if strings:
                return max((text for _, text in strings), key=len)
        except Exception:
            pass
    return _clean_remote_text(body)


def _remote_quality_ok(text: str, minimum: int, maximum: int) -> bool:
    clean = _clean_remote_text(text)
    if len(clean) < minimum or len(clean) > maximum:
        return False
    folded = clean.lower().replace("‌", " ")
    if any(token in folded for token in _REMOTE_BLOCK_PATTERNS):
        return False
    if clean.count("�") > 0:
        return False
    return True


def _remember_remote(scope: str, kind: str, text: str) -> bool:
    digest = hashlib.sha256(_clean_remote_text(text).encode("utf-8", errors="ignore")).hexdigest()[:20]
    history = _remote_history[(scope, kind)]
    if digest in history:
        return False
    history.append(digest)
    return True


async def _fetch_remote_plain(
    url: str,
    scope: str,
    kind: str,
    minimum: int,
    maximum: int,
    attempts: int = 3,
) -> str:
    if not REMOTE_ENABLED or not url:
        return ""
    for _ in range(max(1, attempts)):
        try:
            body, content_type = await _remote_get(url)
            text = _extract_remote_candidate(body, content_type)
            if not _remote_quality_ok(text, minimum, maximum):
                continue
            if not _remember_remote(scope, kind, text):
                continue
            return _clean_remote_text(text)
        except Exception:
            return ""
    return ""


async def _fetch_hafez(scope: str) -> str:
    if not REMOTE_ENABLED or not REMOTE_HAFEZ_URL:
        return ""
    try:
        body, content_type = await _remote_get(REMOTE_HAFEZ_URL)
        body = (body or "").strip()
        if not body:
            return ""
        if "json" in (content_type or "").lower() or body[:1] in "[{":
            try:
                parsed = json.loads(body)
                strings: List[Tuple[str, str]] = []
                _walk_json_strings(parsed, strings)
                poem_parts = [text for key, text in strings if any(k in key for k in ("poem", "ghazal", "fal", "text"))]
                interpretation_parts = [text for key, text in strings if any(k in key for k in ("interpretation", "tafsir", "meaning", "result"))]
                poem = max(poem_parts, key=len) if poem_parts else ""
                interpretation = max(interpretation_parts, key=len) if interpretation_parts else ""
                if poem and len(poem) > 2400:
                    poem = poem[:2400].rsplit(" ", 1)[0] + "…"
                result = poem
                if interpretation and interpretation != poem:
                    if len(interpretation) > 900:
                        interpretation = interpretation[:900].rsplit(" ", 1)[0] + "…"
                    result = f"{poem}\n\n🪶 تعبیر:\n{interpretation}" if poem else interpretation
                result = _clean_remote_text(result)
                if 40 <= len(result) <= 3400 and _remember_remote(scope, "hafez", result):
                    return result
            except Exception:
                pass
        plain = _clean_remote_text(body)
        if 40 <= len(plain) <= 3400 and _remember_remote(scope, "hafez", plain):
            return plain
    except Exception:
        return ""
    return ""


